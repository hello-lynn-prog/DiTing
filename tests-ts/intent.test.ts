test('research intent separates capability questions, report explanations and explicit new investigations',()=>{
  const cases:[string,boolean,string][]=[
    ['什么是舆情分析',false,'question'],['舆情研判和关键词搜索有什么区别',false,'question'],
    ['这个系统如何研究热点',false,'question'],['研究任务为什么失败了',false,'question'],
    ['系统能不能研究视频',false,'question'],['“分析近期 AI 舆情”是什么意思',false,'question'],
    ['能不能帮我研究近7天 AI 行业争议',false,'research'],['请深度研判新能源汽车行业',false,'research'],
    ['分析近期 AI 舆情',false,'research'],['我想研究近30天的食品安全事件',false,'research'],
    ['请深度分析近7天AI行业争议，自动选合适模板，保存全部原文和过程。',false,'research'],
    ['调查近30天，预算10元',false,'clarify'],['分析一下',false,'clarify'],['生成报告',false,'clarify'],
    ['帮我生成一个品牌报告模板',false,'template'],['报告模板是什么',false,'question'],
    ['分析一下这份报告的风险',true,'report_question'],['再分析一下风险和建议',true,'report_question'],
    ['这些数字怎么统计出来的',true,'report_question'],['生成这份报告的摘要',true,'report_question'],
    ['不要重新研究，只解释这张表',true,'report_question'],['为什么报告中建议重新研究',true,'report_question'],
    ['补充研究：联网核实这份报告的风险',true,'research'],['重新调查近7天 AI 行业并出一份新报告',true,'research'],
    ['调查最近7天新能源汽车行业',true,'research'],['舆情分析是什么',true,'report_question'],
  ];
  for(const [text,bound,expected] of cases)assert.equal(classify(text,bound),expected,text);
});

test('a clarified research topic preserves the requested window and budget without reserving a slot early',()=>{
  const dir=mkdtempSync(join(tmpdir(),'diting-intent-')),db=new Database(join(dir,'diting.sqlite3'),ROOT),s=new Service(db);
  try{
    const sid=s.session();const first=s.send(sid,'调查近30天，预算10元','intent-clarify-1');assert.equal(first.intent,'clarify');assert.equal(s.tasks().length,0);
    const result=s.send(sid,'新能源汽车行业争议','intent-clarify-2');assert.equal(result.intent,'research');
    const task=s.task(result.task_id);assert.equal(task.config.window_days,30);assert.equal(task.budget,10);assert.ok(task.title.includes('新能源汽车'));
    assert.equal(s.send(sid,'新能源汽车行业争议','intent-clarify-2').task_id,task.id,'duplicate submission must not create a second task');
    const cancelled=s.session();s.send(cancelled,'研究一下','intent-stop-1');assert.equal(s.send(cancelled,'算了，先不用研究','intent-stop-2').task_id,null);assert.equal(s.send(cancelled,'AI 行业','intent-stop-3').task_id,null);
    const question=s.session();s.send(question,'分析一下','intent-question-1');assert.equal(s.send(question,'你能研究视频吗','intent-question-2').task_id,null,'a clarification must not turn a capability question into paid work');
    // An explicit database fixture, never a report generated by the product.
    db.run('INSERT INTO reports VALUES(?,?,?,?,?,?,?)','report_fixture_intent',task.id,1,'合成分流测试报告','{}','fixture-only',now());
    const bound=s.session('固定报告追问','report_fixture_intent');
    assert.equal(s.send(bound,'分析一下风险和建议','intent-bound-1').intent,'report_question');
    assert.equal(s.tasks().length,1,'explaining an existing report cannot open a new research task');
    const follow=s.send(bound,'补充研究：联网核实报告风险','intent-bound-2');assert.equal(follow.intent,'research');assert.equal(s.task(follow.task_id).parent_id,task.id,'explicit followup research must stay linked to the fixed report lineage');
    assert.equal(db.one('SELECT report_id FROM sessions WHERE id=?',bound)!.report_id,'report_fixture_intent','starting a followup must not overwrite the report conversation binding');
  }finally{db.close();}
});
